type Language = 'en' | 'as';
type TranslationCatalog = Record<string, string>;

const normalize = (value: string) => value.replace(/\u00a0/g, ' ').replace(/\s+/g, ' ').trim();
let activeLanguage: Language = 'en';
let catalog: TranslationCatalog = {};
let reverseCatalog: TranslationCatalog = {};
let observer: MutationObserver | null = null;
type TranslationTask = { root: Node; walker: TreeWalker | null };
const translationTasks: TranslationTask[] = [];
const queuedRoots = new Set<Node>();
const queuedText = new Set<Text>();
let translationScheduled = false;
const originalText = new WeakMap<Text, string>();
const lastRenderedText = new WeakMap<Text, string>();
const originalAttributes = new WeakMap<Element, Map<string, { original: string; rendered: string }>>();

const DYNAMIC_PREFIX_TRANSLATIONS: Array<[string, string]> = [
  ['Student: ', 'শিক্ষাৰ্থী: '],
  ['Signed in as ', 'লগ ইন কৰিছে: '],
  ['Welcome back, ', 'স্বাগতম, '],
  ['Submitting as authenticated student: ', 'প্ৰমাণিত শিক্ষাৰ্থী হিচাপে জমা দিছে: '],
];

function translateValue(_value: string, original: string): string {
  if (activeLanguage === 'en') return original;
  const key = normalize(original);
  const exact = catalog[key];
  if (exact) return exact;
  const trimmed = original.trim();
  const dynamicPrefix = DYNAMIC_PREFIX_TRANSLATIONS.find(([prefix]) => trimmed.startsWith(prefix));
  if (dynamicPrefix) return `${dynamicPrefix[1]}${trimmed.slice(dynamicPrefix[0].length)}`;
  return original;
}

function updateText(node: Text): void {
  if (node.parentElement?.closest('.language-toggle, script, style, textarea, code, pre, [contenteditable="true"], [data-no-translate]')) return;
  const current = node.nodeValue ?? '';
  if (!normalize(current)) return;
  const previous = originalText.get(node);
  const lastRendered = lastRenderedText.get(node);
  if (activeLanguage === 'en' && previous === undefined && !reverseCatalog[normalize(current)]) return;
  const source = previous !== undefined && normalize(current) === normalize(lastRendered ?? previous)
    ? previous
    : reverseCatalog[normalize(current)] ?? current;
  originalText.set(node, source);
  const match = current.match(/^(\s*)([\s\S]*?)(\s*)$/);
  const next = `${match?.[1] ?? ''}${translateValue(current, source)}${match?.[3] ?? ''}`;
  lastRenderedText.set(node, next);
  if (next !== current) node.nodeValue = next;
}

const TRANSLATABLE_ATTRIBUTES = ['aria-label', 'title', 'placeholder', 'alt'] as const;
function updateAttributes(element: Element): void {
  if (element.closest('.language-toggle, script, style, textarea, code, pre, [contenteditable="true"], [data-no-translate]')) return;
  let originals = originalAttributes.get(element);
  if (!originals && activeLanguage === 'en') return;
  if (!originals) { originals = new Map(); originalAttributes.set(element, originals); }
  for (const name of TRANSLATABLE_ATTRIBUTES) {
    if (!element.hasAttribute(name)) continue;
    const current = element.getAttribute(name) ?? '';
    if (!normalize(current)) continue;
    const previous = originals.get(name);
    if (activeLanguage === 'en' && !previous && !reverseCatalog[normalize(current)]) continue;
    const source = previous !== undefined && normalize(current) === normalize(previous.rendered)
      ? previous.original : reverseCatalog[normalize(current)] ?? current;
    const next = translateValue(current, source);
    if (next === current) continue;
    originals.set(name, { original: source, rendered: next });
    if (next !== current) element.setAttribute(name, next);
  }
}

function enqueueTranslation(root: Node): void {
  if (root.nodeType === Node.TEXT_NODE) {
    const text = root as Text;
    if (queuedText.has(text)) return;
    queuedText.add(text);
  } else {
    if (queuedRoots.has(root)) return;
    queuedRoots.add(root);
  }
  translationTasks.push({ root, walker: null });
  scheduleTranslation();
}

function scheduleTranslation(): void {
  if (translationScheduled || !translationTasks.length) return;
  translationScheduled = true;
  window.setTimeout(processTranslationBatch, 0);
}

function processTranslationBatch(): void {
  translationScheduled = false;
  const started = performance.now();
  let processed = 0;

  while (translationTasks.length && processed < 120 && performance.now() - started < 8) {
    const task = translationTasks[0];
    if (task.root !== document.body && !document.body.contains(task.root)) {
      queuedRoots.delete(task.root);
      queuedText.delete(task.root as Text);
      translationTasks.shift();
      continue;
    }
    if (task.root.nodeType === Node.TEXT_NODE) {
      updateText(task.root as Text);
      queuedText.delete(task.root as Text);
      translationTasks.shift();
      processed++;
      continue;
    }

    if (!task.walker) {
      if (task.root instanceof Element) updateAttributes(task.root);
      task.walker = document.createTreeWalker(task.root, NodeFilter.SHOW_ELEMENT | NodeFilter.SHOW_TEXT);
    }
    const node = task.walker.nextNode();
    if (!node) {
      queuedRoots.delete(task.root);
      translationTasks.shift();
      continue;
    }
    if (node.nodeType === Node.TEXT_NODE) updateText(node as Text);
    else updateAttributes(node as Element);
    processed++;
  }

  scheduleTranslation();
}

export function applyUiLanguage(language: Language, knownTranslations: Record<string, string>): void {
  const changed = language !== activeLanguage;
  activeLanguage = language;
  if (changed || !observer) {
    const allTranslations = { ...knownTranslations, ...ASSAMESE_UI_TEXT };
    catalog = language === 'as' ? allTranslations : {};
    reverseCatalog = Object.fromEntries(Object.entries(allTranslations).map(([en, as]) => [normalize(as), en]));
  }
  document.documentElement.lang = language;
  if (!document.body) return;
  if (!observer) {
    observer = new MutationObserver((records) => {
      for (const record of records) {
        if (record.type === 'characterData' && record.target instanceof Text) {
          if (activeLanguage === 'as' || originalText.has(record.target)) enqueueTranslation(record.target);
        }
        if (record.type === 'attributes' && record.target instanceof Element) {
          if (activeLanguage === 'as' || originalAttributes.has(record.target)) enqueueTranslation(record.target);
        }
        if (activeLanguage === 'as') record.addedNodes.forEach(enqueueTranslation);
      }
    });
    observer.observe(document.body, { subtree: true, childList: true, characterData: true, attributes: true, attributeFilter: [...TRANSLATABLE_ATTRIBUTES] });
  }
  if (changed && language === 'as') enqueueTranslation(document.body);
  else if (changed && language === 'en') enqueueTranslation(document.body);
}
